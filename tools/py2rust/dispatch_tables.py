"""Emit reader/writer dispatch tables for ported handlers (P5, roadmap §6).

Grounded in two generated artifacts:
- src/m2/element_registry.rs: the (tag -> ElementRef variant) pairs a package
  element can carry — the dispatch knowledge itself;
- the `fn <snake_case>` existence scan (port_checklist.collect_fn_names):
  entries exist only for handlers present in src/, so regenerating after a
  family lands grows the tables.

Each entry routes through a generated *shim* fn: the shim destructures the
ElementRef to the typed id (reader) and monomorphizes the emitter at
W = &mut dyn Write (writer), so table entries are plain fn pointers while the
hand-written handlers keep their existing signatures.

AR-PACKAGE is excluded: packages are walked by read_ar_packages/write_ar_packages
and never reach the read_element_payload / write_ar_package_element seams.
"""
import pathlib
import re
import shutil
import subprocess
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from port_checklist import collect_fn_names, rust_name  # noqa: E402

READER_TABLE_NAME = "READ_TABLE"
WRITER_TABLE_NAME = "WRITE_TABLE"

READER_TEMPLATE = """//! GENERATED by tools/py2rust --emit-dispatch-tables. DO NOT EDIT.
//! Tag-keyed reader dispatch table (P5, roadmap 2026-10-03 §6). Entries exist
//! only for handler fns present in src/ — regenerate after landing families.
use super::*;

pub(crate) type ReadHandler =
    fn(&mut ARXMLReader, &Node, ElementRef, &mut Document) -> Result<(), ParseError>;

pub(crate) static {table}: LazyLock<Vec<(&'static str, ReadHandler)>> =
    LazyLock::new(|| vec![
{reader_entries}]);

pub(crate) fn lookup_read_handler(tag: &str) -> Option<ReadHandler> {{
    {table}
        .binary_search_by(|entry| entry.0.cmp(tag))
        .ok()
        .map(|index| {table}[index].1)
}}

{reader_shims}
"""

WRITER_TEMPLATE = """//! GENERATED by tools/py2rust --emit-dispatch-tables. DO NOT EDIT.
//! ElementRef-variant-keyed writer dispatch table (P5, roadmap §6). Entries
//! exist only for handler fns present in src/ — regenerate after landing
//! families. Shims monomorphize each handler at W = &mut dyn Write so the
//! hand-written emitters keep their generic signatures.
use super::*;

pub(crate) type WriteHandler =
    fn(&ARXMLWriter, &mut Writer<&mut dyn std::io::Write>, ElementRef, &Document)
        -> Result<(), WriteError>;

pub(crate) fn variant_index(element: &ElementRef) -> Option<usize> {{
    let index: usize = match element {{
{index_arms}        _ => return None,
    }};
    Some(index)
}}

pub(crate) static {table}: LazyLock<Vec<(usize, WriteHandler)>> =
    LazyLock::new(|| vec![
{writer_entries}]);

pub(crate) fn lookup_write_handler(index: usize) -> Option<WriteHandler> {{
    {table}
        .binary_search_by(|entry| entry.0.cmp(&index))
        .ok()
        .map(|idx| {table}[idx].1)
}}

impl ARXMLWriter {{
{writer_shims}}}
"""

READER_ENTRY = '    ("{tag}", shim_read_{snake}),\n'
READER_SHIM = """    /// Dispatch shim for `{tag}` (ElementRef::`{variant}`).
    fn shim_read_{snake}(
        reader: &mut ARXMLReader,
        element: &Node,
        element_ref: ElementRef,
        document: &mut Document,
    ) -> Result<(), ParseError> {{
        let ElementRef::{variant}(id) = element_ref else {{
            return Ok(());
        }};
        reader.read_{snake}(element, id, document)
    }}
"""

WRITER_INDEX_ARM = "        ElementRef::{variant}(_) => {index},\n"
WRITER_ENTRY = "    ({index}, ARXMLWriter::shim_write_{snake}),\n"
WRITER_SHIM = """    /// Dispatch shim for `ElementRef::{variant}`.
    fn shim_write_{snake}(
        &self,
        serializer: &mut Writer<&mut dyn std::io::Write>,
        element_ref: ElementRef,
        document: &Document,
    ) -> Result<(), WriteError> {{
        let ElementRef::{variant}(id) = element_ref else {{
            return Ok(());
        }};
        self.write_{snake}(serializer, id, document)
    }}
"""


def collect_registry_pairs(src_root: pathlib.Path) -> list[tuple[str, str]]:
    """(tag, variant) pairs from the generated element registry's element_tag
    match (one arm per variant: `ElementRef::X(_) => "X-TAG",`)."""
    registry = src_root / "m2" / "element_registry.rs"
    arms = re.findall(r'ElementRef::([A-Za-z0-9_]+)\(_\) => "([A-Z0-9-]+)"', registry.read_text())
    return [(tag, variant) for variant, tag in arms]


def _rustfmt(path: pathlib.Path) -> None:
    subprocess.run(["rustfmt", "--edition", "2021", str(path)], check=True)


def emit_dispatch_tables(src_root: pathlib.Path) -> tuple[pathlib.Path, pathlib.Path]:
    fn_names = collect_fn_names(src_root)
    reader_rows, writer_rows = [], []
    for tag, variant in collect_registry_pairs(src_root):
        if tag == "AR-PACKAGE":
            continue  # walked by read/write_ar_packages, never reaches the seams
        snake = rust_name(variant)
        if f"read_{snake}" in fn_names:
            reader_rows.append((tag, snake))
        if f"write_{snake}" in fn_names:
            writer_rows.append((variant, snake))

    reader_rows.sort()
    writer_rows.sort()
    reader_entries = "".join(READER_ENTRY.format(tag=tag, snake=snake) for tag, snake in reader_rows)
    reader_shims = "".join(
        READER_SHIM.format(tag=tag, snake=snake, variant=_pascal(snake)) for tag, snake in reader_rows
    )
    reader_path = src_root / "reader" / "arxml_reader" / "dispatch_tables.rs"
    reader_path.parent.mkdir(parents=True, exist_ok=True)
    reader_path.write_text(
        READER_TEMPLATE.format(table=READER_TABLE_NAME, reader_entries=reader_entries, reader_shims=reader_shims)
    )
    _rustfmt(reader_path)

    index_arms = "".join(
        WRITER_INDEX_ARM.format(variant=variant, index=index)
        for index, (variant, _snake) in enumerate(writer_rows)
    )
    writer_entries = "".join(
        WRITER_ENTRY.format(index=index, snake=snake) for index, (_variant, snake) in enumerate(writer_rows)
    )
    writer_shims = "".join(
        WRITER_SHIM.format(variant=variant, snake=snake) for variant, snake in writer_rows
    )
    writer_path = src_root / "writer" / "arxml_writer" / "dispatch_tables.rs"
    writer_path.parent.mkdir(parents=True, exist_ok=True)
    writer_path.write_text(
        WRITER_TEMPLATE.format(table=WRITER_TABLE_NAME, index_arms=index_arms, writer_entries=writer_entries, writer_shims=writer_shims)
    )
    _rustfmt(writer_path)
    return reader_path, writer_path


def _pascal(snake: str) -> str:
    return "".join(part.capitalize() for part in snake.split("_"))
